from pathlib import Path
from datetime import datetime, timedelta

import pandas as pd


# ============================================================
# 1. 入出力フォルダを設定する
# ============================================================

INPUT_DIR = Path("./input")
OUTPUT_DIR = Path("./output")

# outputフォルダがなければ作成する
OUTPUT_DIR.mkdir(exist_ok=True)


# ============================================================
# 2. 処理対象のExcelファイルを取得する
# ============================================================

files = [
    file
    for file in INPUT_DIR.glob("*.xlsx")
    if not file.name.startswith("~$")
]


# ============================================================
# 3. 売上日を正規化する関数
# ============================================================

def normalize_date(value):
    """
    売上日の値をdatetime型に統一する。

    - datetime型 → そのまま返す
    - int型      → Excelの日付シリアル値として変換
    - その他     → Noneを返す
    """

    # datetime型なら、そのまま返す
    if isinstance(value, datetime):
        return value

    # int型なら、Excelの日付シリアル値として変換する
    elif isinstance(value, int):
        return datetime(1899, 12, 30) + timedelta(days=value)

    # "-", "不明" など、それ以外の値はNoneにする
    else:
        return None


# ============================================================
# 4. 金額を正規化する関数
# ============================================================

def normalize_amount(value):
    """
    金額を数値に統一する。

    - int / float型 → そのまま返す
    - str型         → "," と "円" を削除して数値に変換
    - 変換できない値 → Noneを返す
    """

    # 数値なら、そのまま返す
    if isinstance(value, (int, float)):
        return value

    # 文字列なら、不要な文字を削除して数値に変換する
    elif isinstance(value, str):
        value = value.replace(",", "").replace("円", "").strip()

        try:
            return int(value)
        except ValueError:
            return None

    # それ以外は不正値として扱う
    else:
        return None


# ============================================================
# 5. Excelファイルを1つずつ処理する
# ============================================================

for file in files:

    print("=" * 60)
    print("Excel / CSV Data Cleaner")
    print("=" * 60)

    # --------------------------------------------------------
    # 5-1. Excelファイルを読み込む
    # --------------------------------------------------------

    print(f"\n処理対象: {file.name}")

    df = pd.read_excel(file)


    # --------------------------------------------------------
    # 5-2. 列名を正規化する
    # --------------------------------------------------------

    # 列名の前後にある空白を削除する
    df.columns = df.columns.str.strip()


    # --------------------------------------------------------
    # 5-3. データを正規化する
    # --------------------------------------------------------

    # 売上日を正規化する
    df["売上日"] = df["売上日"].apply(normalize_date)

    # 金額を正規化する
    df["金額"] = df["金額"].apply(normalize_amount)


    # --------------------------------------------------------
    # 5-4. データのエラーを検出する
    # --------------------------------------------------------

    # エラー内容を格納する列を追加する
    df["エラー内容"] = ""

    # 商品コードが欠損している場合
    df.loc[
        df["商品コード"].isna(),
        "エラー内容"
    ] += "商品コードがありません / "

    # 売上日が欠損・不正な場合
    df.loc[
        df["売上日"].isna(),
        "エラー内容"
    ] += "売上日が不正です / "

    # 金額が欠損・不正な場合
    df.loc[
        df["金額"].isna(),
        "エラー内容"
    ] += "金額が不正です / "


    # --------------------------------------------------------
    # 5-5. 正常データとエラーデータに分ける
    # --------------------------------------------------------

    error_rows = df[
        df["エラー内容"] != ""
    ]

    normal_rows = df[
        df["エラー内容"] == ""
    ]


    # --------------------------------------------------------
    # 5-6. 処理結果をターミナルに表示する
    # --------------------------------------------------------

    print(f"読み込み件数: {len(df)}件")

    print("\n[処理結果]")
    print(f"正常: {len(normal_rows)}件")
    print(f"エラー: {len(error_rows)}件")

    print("\n[エラー詳細]")

    if error_rows.empty:
        print("エラーはありません。")
    else:
        print(error_rows.to_string(index=False))


    # --------------------------------------------------------
    # 5-7. 処理結果をExcelファイルに出力する
    # --------------------------------------------------------

    cleaned_file = OUTPUT_DIR / f"cleaned_{file.name}"
    error_file = OUTPUT_DIR / f"errors_{file.name}"

    # 正常データを出力する
    normal_rows.to_excel(
        cleaned_file,
        index=False
    )

    # エラーデータを出力する
    error_rows.to_excel(
        error_file,
        index=False
    )


    # --------------------------------------------------------
    # 5-8. 出力先を表示する
    # --------------------------------------------------------

    print("\n[出力ファイル]")
    print(f"正常データ: {cleaned_file}")
    print(f"エラーデータ: {error_file}")

    print("\n" + "=" * 60)
    print("処理完了")
    print("=" * 60)